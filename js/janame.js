// 히라가나·반각 → 전각 가타카나
export function toKatakana(t){
  return String(t || '').normalize('NFKC').replace(/[ぁ-ゖ]/g, c => String.fromCharCode(c.charCodeAt(0) + 0x60));
}

// 가타카나 한 낱말 → 한글 (사전을 거치지 않은 일본어 낱말용)
export function kanaToHangul(word){
  const w = toKatakana(word); let out = ''; let lastV = '';
  const addJong = jong => { if(!out) return; const c = out.charCodeAt(out.length - 1) - 0xAC00;
    if(c >= 0 && c < 11172 && c % 28 === 0) out = out.slice(0, -1) + String.fromCharCode(0xAC00 + c + jong); };
  for(let i = 0; i < w.length; i++){
    const k = w[i], nx = w[i + 1] || ''; const first = !out;
    if(k === 'ー') continue;                                     // 긴소리는 적지 않음
    if(k === 'ッ'){ addJong(19); continue; }                      // ㅅ받침
    if(k === 'ン'){ if(out) addJong(4); else out += '응'; lastV = ''; continue; }   // ㄴ받침
    const two = k + nx;
    if(FOREIGN[two]){ out += FOREIGN[two]; lastV = FOREIGN_V[FOREIGN[two]]; i++; continue; }
    if(SMALL_Y[nx] && KANA[k] && KANA[k][2] === 'i' && k !== 'イ'){   // キャ·シュ·チョ…
      const [c0, c1] = KANA[k]; const cho = first ? c0 : c1; const v = SMALL_Y[nx];
      const plain = cho === 12 || cho === 14;                     // ジャ·チャ → 자·차 (ㅈ·ㅊ 뒤 이중모음은 쓰지 않음)
      out += syl(cho, plain ? JUNG[v] : JUNG['y' + v]); lastV = v; i++; continue;
    }
    if((k === 'ウ' && (lastV === 'o' || lastV === 'u')) || (k === 'オ' && lastV === 'o')){ lastV = ''; continue; }   // 도우 → 도
    const m = KANA[k]; if(!m){ out += k; lastV = ''; continue; }
    out += syl(first ? m[0] : m[1], jungOf(m[2]));
    lastV = m[2] === 'eu' ? 'u' : m[2].replace(/^[yw]/, '');
  }
  return out;
}

