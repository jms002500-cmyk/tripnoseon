function nameToKana(name){
  let t = toKatakana(name); let out = '';
  while(t){
    const hit = KANJI.find(([k]) => t.startsWith(k));
    if(hit){ out += ' ' + hit[1] + ' '; t = t.slice(hit[0].length); continue; }
    if(/[一-鿿々]/.test(t[0])) return '';
    out += t[0]; t = t.slice(1);
  }
  return out;
}

