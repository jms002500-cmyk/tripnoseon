// 가타카나 이름 → 낱말로 나눠 한글로. 사전 낱말은 그대로, 나머지 일본어는 소리대로
//   짧은 사전 낱말(2자 이하: イン·ザ·アパ…)은 낱말 경계에서만 맞춤 (シンジュク 안의 'イン' 같은 오인 방지)
export function kanaNameToKo(kana){
  const w = toKatakana(kana); const out = []; let unk = ''; let edge = true;
  const flush = () => {
    if(!unk) return;
    unk.split(/([^ァ-ヺー]+)/).filter(Boolean).forEach(p => out.push(isKana(p[0]) ? kanaToHangul(p) : p));
    unk = '';
  };
  for(let i = 0; i < w.length;){
    if(SEP.test(w[i])){ flush(); edge = true; i++; continue; }
    const key = KEYS.find(k => (k.length >= 3 || edge) && w.startsWith(k, i));
    if(key){ flush(); out.push(DICT[key]); i += key.length; edge = true; continue; }
    unk += w[i]; i++; edge = false;
  }
  flush();
  return out.join(' ').replace(/\s+/g, ' ').trim();
}

